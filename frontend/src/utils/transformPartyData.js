// Transformar de camelCase (frontend) a snake_case (backend)
export const transformToSnakeCase = (data) => {
  return {
    document_number: data.documentNumber,
    names: data.names?.toUpperCase(),
    last_names: data.lastNames?.toUpperCase(),
    document_type: data.documentType?.toLowerCase(),
    gender: data.gender?.toLowerCase(),
    marital_status: data.maritalStatus?.toLowerCase(),
    partner_document_number: data.partnerDocumentNumber || null,
    nationality: data.nationality,
    birth_date: data.birthDate,
    email: data.email?.toLowerCase(),
    phone: data.phone,
    province: data.province,
    canton: data.canton,
    parroquia: data.parroquia,
    sector: data.sector || null,
    main_street: data.mainStreet,
    secondary_street: data.secondaryStreet,
    number_street: data.numberStreet,
    occupation: data.occupation,
    profession: data.profession || null,
  };
};

// Transformar de snake_case (backend) a camelCase (frontend)
export const transformToCamelCase = (data) => {
  if (!data) return null;

  // Si es una empresa (tiene ruc en lugar de document_number)
  if (data.ruc) {
    return {
      esEmpresa: true,
      ruc: data.ruc || "",
      razonSocial: data.razon_social || "",
      email: data.email || "",
      phone: data.phone || "",
      province: data.province || "",
      canton: data.canton || "",
      parroquia: data.parroquia || "",
      sector: data.sector || "",
      mainStreet: data.main_street || "",
      secondaryStreet: data.secondary_street || "",
      numberStreet: data.number_street || "",
      // Representante legal
      repDocumentType: data.rep_document_type || "cedula",
      repDocumentNumber: data.rep_document_number || "",
      repNames: data.rep_names || "",
      repLastNames: data.rep_last_names || "",
      repGender: data.rep_gender || "",
      repNationality: data.rep_nationality || "",
      repBirthDate: data.rep_birth_date || "",
      repEmail: data.rep_email || "",
      repPhone: data.rep_phone || "",
      repProvince: data.rep_province || "",
      repCanton: data.rep_canton || "",
      repParroquia: data.rep_parroquia || "",
      repSector: data.rep_sector || "",
      repMainStreet: data.rep_main_street || "",
      repSecondaryStreet: data.rep_secondary_street || "",
      repNumberStreet: data.rep_number_street || "",
      repOccupation: data.rep_occupation || "",
      repProfession: data.rep_profession || "",
      repPosition: data.rep_position || "",
      // Información financiera / UAFE de la empresa
      ingresoMensual: data.ingreso_mensual ?? "",
      egresoMensual: data.egreso_mensual ?? "",
      actividadEmpresa: data.actividad_empresa || "",
      rolTramite: data.rol_tramite || "",
      origenFondos: data.origen_fondos || "",
      controladaSupercias: data.controlada_supercias ?? null,
      socios: data.socios || [],
      referenciaSupercias: data.referencia_supercias || "",
      anexoSociosNombre: data.anexo_socios_nombre || "",
      // Información financiera / UAFE del representante legal
      repActividadEconomica: data.rep_actividad_economica || "",
      repEmpresaTrabajo: data.rep_empresa_trabajo || "",
      repIngresoMensual: data.rep_ingreso_mensual ?? "",
      repRolTramite: data.rep_rol_tramite || "",
      repOrigenFondos: data.rep_origen_fondos || "",
      repEsPep: data.rep_es_pep ?? null,
      repEsPepIndirecto: data.rep_es_pep_indirecto ?? null,
      repPepNombre: data.rep_pep_nombre || "",
      repPepInstitucion: data.rep_pep_institucion || "",
      repPepCargo: data.rep_pep_cargo || "",
      repPepFechaInicio: data.rep_pep_fecha_inicio || "",
      repPepYaNoEjerce: data.rep_pep_ya_no_ejerce === true,
      repPepFechaFin: data.rep_pep_fecha_fin || "",
      repPepRelacionTipo: data.rep_pep_relacion_tipo || "",
      repPepGradoRelacion: data.rep_pep_grado_relacion || "",
      repPatrimonio: data.rep_patrimonio || null,
      // Declaraciones UAFE y cambios reportados pendientes de revisión
      declaraciones: data.declaraciones || [],
      datosReportadosPendientes: data.datos_reportados_pendientes || [],
      repDatosReportadosPendientes: data.rep_datos_reportados_pendientes || [],
    };
  }

  // Persona natural
  return {
    esEmpresa: false,
    documentNumber: data.document_number || "",
    names: data.names || "",
    lastNames: data.last_names || "",
    documentType: data.document_type || "cedula",
    gender: data.gender || "",
    maritalStatus: data.marital_status || "",
    partnerDocumentNumber: data.partner_document_number || null,
    nationality: data.nationality || "ecuatoriana",
    birthDate: data.birth_date || "",
    email: data.email || "",
    phone: data.phone || "",
    province: data.province || "",
    canton: data.canton || "",
    parroquia: data.parroquia || "",
    sector: data.sector || "",
    mainStreet: data.main_street || "",
    secondaryStreet: data.secondary_street || "",
    numberStreet: data.number_street || "",
    edificio: data.edificio || "",
    occupation: data.occupation || "",
    profession: data.profession || "",
    conyugueComparece: data.conyugue_comparece !== false,
    razonExclusionConyugue: data.razon_exclusion_conyugue || "",
    actividadEconomica: data.actividad_economica || "",
    empresaTrabajo: data.empresa_trabajo || "",
    ingresoMensual: data.ingreso_mensual ?? "",
    origenFondos: data.origen_fondos || "",
    esPep: data.es_pep,
    esPepIndirecto: data.es_pep_indirecto,
    pepNombre: data.pep_nombre || "",
    pepInstitucion: data.pep_institucion || "",
    pepFechaInicio: data.pep_fecha_inicio || "",
    pepCargo: data.pep_cargo || "",
    pepAniosTrabajo: data.pep_anios_trabajo || "",
    pepGradoRelacion: data.pep_grado_relacion || "",
    pepRelacionTipo: data.pep_relacion_tipo || "",
    pepYaNoEjerce: data.pep_ya_no_ejerce === true,
    pepFechaFin: data.pep_fecha_fin || "",
    patrimonio: data.patrimonio || null,
    rolTramite: data.rol_tramite || "",
    declaraciones: data.declaraciones || [],
    datosReportadosPendientes: data.datos_reportados_pendientes || [],
    partner: data.partner ? transformToCamelCase(data.partner) : null,
  };
};
